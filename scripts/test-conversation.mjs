import assert from 'node:assert/strict';
import {loader} from './test-loader.mjs';
const {ConversationController}=await loader()('lib/conversation.ts');
const p={text:'Lunch at CMU.',dims:['health'],reason:'Nutrition.',emotion:null,confidence:.95,date:'2026-09-12'};
const result={reply:'Ready for review.',changes:[{cardId:null,proposal:p}]};
const c=new ConversationController();let persisted;c.hydrate(null,value=>persisted=value);
c.message('user','I ate lunch at CMU.');let req=c.begin();c.apply(req,result);c.finish(req);
const id=c.getSnapshot().cards[0].id;
c.switchMode('voice');assert.equal(c.context().history[0].inputMode,'text');
c.message('user','Actually, yesterday.');req=c.begin();c.apply(req,{reply:'Updated.',changes:[{cardId:id,proposal:{...p,date:'2026-09-11'}}]});c.finish(req);
assert.equal(c.getSnapshot().cards.length,1);assert.equal(c.getSnapshot().cards[0].date,'2026-09-11');
req=c.begin();c.edit(id,{...p,text:'My own edited lunch.'});assert.equal(c.apply(req,result.changes.length?{reply:'Updated.',changes:[{cardId:id,proposal:p}]}:result).conflicts,1);c.finish(req);
let finishSave;const save=c.save([id],()=>new Promise(resolve=>finishSave=resolve));
req=c.begin();c.message('user','unfinished','partial','partial');c.switchMode('text');
assert(req.signal.aborted);assert.equal(c.apply(req,result).count,0);assert(!c.context().history.some(e=>e.id==='partial'));
finishSave();await save;assert.equal(c.getSnapshot().cards[0].status,'saved');assert(c.context().history.some(e=>e.text.startsWith('Save succeeded')));
assert.equal(persisted.cards[0].status,'saved','Save survives mode switch and persists');
req=c.begin();assert.equal(c.apply(req,{reply:'Updated.',changes:[{cardId:id,proposal:p}]}).conflicts,1);c.finish(req);
req=c.begin();c.apply(req,{reply:'New.',changes:[{cardId:null,proposal:{...p,text:'Hiking.'}}]});c.finish(req);const second=c.getSnapshot().cards[1].id;
await c.save([second],async()=>{throw new Error('offline')});assert.equal(c.getSnapshot().cards[1].status,'draft');assert.equal(c.getSnapshot().error,'offline');
c.discard([second]);assert.equal(c.getSnapshot().cards[1].status,'discarded');
const restored=new ConversationController();restored.hydrate(persisted,()=>{});assert.deepEqual(restored.context().cards,c.context().cards);
const legacy=new ConversationController();legacy.hydrate({msgs:[{who:'me',text:'old'}],items:[p]},()=>{});assert.equal(legacy.getSnapshot().cards.length,1);
console.log('Shared conversation passed: cross-mode correction, stable IDs, edit conflicts, cancellation, partial removal, independent Save, failure/retry state, discard and hydration.');

const originalId=c.getSnapshot().conversationId;
c.setDraft('A thought to finish later');c.switchMode('voice');
req=c.begin();c.message('assistant','unfinished output','switch-partial','partial');
assert.equal(c.openConversation(),true);assert(req.signal.aborted);
assert.equal(c.apply(req,result).count,0,'Late results cannot enter the new conversation');
assert.equal(c.getSnapshot().mode,'text');assert.deepEqual(c.context().history,[]);assert.deepEqual(c.context().cards,[]);
assert.equal(c.getSnapshot().draft,'');assert.equal(c.getSnapshot().archives.length,1);
assert(!c.getSnapshot().archives[0].history.some(e=>e.status==='partial'));
c.message('user','This is a different conversation.');
const newId=c.getSnapshot().conversationId;
assert.equal(c.openConversation(originalId),true);
assert.equal(c.getSnapshot().draft,'A thought to finish later');assert.equal(c.getSnapshot().cards[0].status,'saved');
assert(!c.context().history.some(e=>e.text==='This is a different conversation.'));
const reload=new ConversationController();reload.hydrate(persisted,()=>{});
assert.equal(reload.getSnapshot().conversationId,originalId);assert.equal(reload.openConversation(newId),true);
assert.equal(reload.context().history[0].text,'This is a different conversation.');
req=reload.begin();reload.apply(req,result);reload.finish(req);
let resolveSave;const pendingSave=reload.save([reload.getSnapshot().cards[0].id],()=>new Promise(resolve=>resolveSave=resolve));
assert.equal(reload.openConversation(),false);assert.equal(reload.openConversation(originalId),false);
resolveSave();await pendingSave;
assert.equal(reload.openConversation(originalId),true);
assert.equal(reload.openConversation(newId),true);assert.equal(reload.getSnapshot().cards[0].status,'saved');
console.log('Conversation threads passed: isolated context, archive/reopen, persisted drafts and saved state, partial removal, stale-result rejection, and Save guard.');
